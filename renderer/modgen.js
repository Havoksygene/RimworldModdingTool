    const races = (it.races || ['Human']).filter(okId);
    if (races.some((r) => r !== 'Human')) ctx.warn(it, 'Installing on animals, mechanoids or other races uses the same surgery as for humans, but has not been tried in game. The body parts must exist on those races, and a picture drawn on the pawn is placed for humans, so check it on animals.');
