      chunk = !!P.chunk;
    const tex = `Things/Item/${chunk ? 'Chunk' : 'Resource'}/${ctx.slug}/${it.defName}`;
    const files = [];
    const s = firstRef(it.sprites.single) || firstRef(it.sprites.main);
