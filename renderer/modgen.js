        const stage = [];
        if (num(it.highHunger) !== null && Number(num(it.highHunger)) !== 0) stage.push(x('hungerRateFactorOffset', num(it.highHunger)));
        if (num(it.highPain) !== null && Number(num(it.highPain)) !== 0) stage.push(x('painOffset', num(it.highPain)));
