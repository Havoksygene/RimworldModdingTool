  // Wall: structure copied from the vanilla Wall (Buildings_Structure.xml) and Sandbags (single sheet). Not loaded in game yet.
  // Natural rock (mountain stone or ore vein): ThingDef based on UglyRockBase / RockBase like vanilla Granite and MineableSteel.
  function genRock(it, ctx) {
    ctx.warn(
      it,
      'Rock XML is copied from the structure of vanilla Granite and compacted steel but has not been loaded in game yet. Note: the game chooses which rocks appear on a map in its own program, so this rock is mined normally but only shows up on maps through other mods or patches.',
    );
    const ore = it.rockKind === 'ore';
    const base = `Things/Building/${ctx.slug}`;
    const files = [];
    const ref = firstRef(it.sprites.atlas);
    if (ref) files.push({ path: `Textures/${base}/${it.defName}_Atlas.png`, sprite: ref, keep: true });
    else ctx.warn(it, 'No rock sheet chosen: the rock will be invisible.');
    const hex = /^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(clean(it.color));
    if (clean(it.color) && !hex) ctx.warn(it, 'The tint colour must look like #695f61; it was left out.');
    const mt = clean(it.mineableThing);
    if (!/^[A-Za-z0-9_]*$/.test(mt)) ctx.warn(it, `"${mt}" is not a valid ID; mining would give nothing.`);
    if (!mt) ctx.warn(it, ore ? 'No resource chosen: mining the ore gives nothing.' : 'No chunk chosen: mining this rock never drops a chunk.');
    const hp = SCHEMA.BUILDING_STATS.filter(([k]) => k === 'MaxHitPoints' || k === 'Beauty');
    const sn = statNodes(it, hp).filter((n) => n.name !== 'WorkToBuild');
    const b = [];
    if (ore) {
      b.push(x('isResourceRock', 'true'));
      if (mt) b.push(x('mineableThing', mt));
      const y = Math.round(Number(it.mineableYield));
      if (y > 0) b.push(x('mineableYield', String(y)));
      const c = num(it.veinCommonality);
      if (c !== null && Number(c) > 0) b.push(x('mineableScatterCommonality', c));
      if (/^\d+~\d+$/.test(clean(it.veinSize))) b.push(x('mineableScatterLumpSizeRange', clean(it.veinSize)));
      b.push(x('veinMineable', 'true'));
    } else {
      if (mt) b.push(x('mineableThing', mt));
      const d = num(it.dropChance);
      b.push(x('mineableDropChance', d !== null ? d : '0.25'));
    }
    const kids = [
      x('defName', it.defName),
      x('label', it.label),
      x('description', describe(it, ctx)),
      x('graphicData', [
        x('texPath', `${base}/${it.defName}_Atlas`),
        x('graphicClass', 'Graphic_Single'),
        it.linkStyle === 'Basic' ? x('linkType', 'Basic') : null,
        hex ? x('color', `(${parseInt(hex[1], 16)},${parseInt(hex[2], 16)},${parseInt(hex[3], 16)})`) : null,
      ]),
      sn.length ? x('statBases', sn) : null,
      x('building', b),
    ];
    return { dir: 'Defs/ThingDefs_Buildings', xml: doc(x('Defs', [x('ThingDef', kids, { ParentName: ore ? 'RockBase' : 'UglyRockBase' })])), files };
  }

