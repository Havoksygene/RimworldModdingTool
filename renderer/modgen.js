  function genBiome(it, ctx, project) {
    ctx.warn(
      it,
      'Biome XML is copied from the vanilla temperate forest but has not been loaded in game yet. If the game reports an error, send me the log.',
    );
    const tex = `World/Biomes/${ctx.slug}/${it.defName}`;
    const files = [];
    const sp = firstRef(it.sprites.single);
    if (sp) files.push({ path: `Textures/${tex}.png`, sprite: sp, keep: true });
    else ctx.warn(it, 'No world map picture chosen: the biome will show a red error tile on the world map.');
    const may = (id) => {
      const pk = SCHEMA.CATALOG.dlcPackage[SCHEMA.CATALOG.srcOf[id]];
      return pk ? { MayRequire: pk } : undefined;
    };
    const idOk = (id) => /^[A-Za-z0-9_]+$/.test(String(id || ''));
    const n = (v, d) => (num(v) !== null ? String(num(v)) : String(d));
    const wild = (list, kind, label) => {
      const rows = SCHEMA.resolveWild(list, kind, project),
        out = [];
      for (const r of rows) {
        if (!idOk(r.id)) {
          ctx.warn(it, `${label}: "${r.id}" is not a valid ID and was left out.`);
          continue;
        }
        const c = num(r.commonality);
        out.push(x(r.id, c !== null ? String(c) : '1', may(r.id)));
      }
      for (const e of list || [])
        if (e && e.rule && !SCHEMA.matchRule(e, kind, project).length)
          ctx.warn(it, `${label}: a rule matches nothing (${e.stat || 'no stat chosen'}). Scan the mods that add them, or check the number.`);
      return out;
    };
    const plants = wild(it.wildPlants, 'plants', 'Wild plants'),
      animals = wild(it.wildAnimals, 'animals', 'Wild animals');
    if (!plants.length) ctx.warn(it, 'No wild plants: the map will be bare.');
    if (!animals.length) ctx.warn(it, 'No wild animals.');
    const band = (b) => x('li', [x('terrain', b.terrain), x('min', n(b.min, -999)), x('max', n(b.max, 999))]);
    const bands = (it.terrains || []).filter((b) => b && idOk(b.terrain));
    if (!bands.length) ctx.warn(it, 'No ground chosen under "Ground by fertility": maps would have no floor.');
    const patches = (it.patches || []).map((p) =>
      x('li', [
        x('perlinFrequency', n(p.freq, 0.015)),
        p.pond ? x('isPond', 'true') : null,
        x('thresholds', (p.bands || []).filter((b) => b && idOk(b.terrain)).map(band)),
      ]),
    );
    const pairs = (arr, a, b) => (arr || []).filter((c) => c && idOk(c.name) && num(c.value) !== null).map((c) => [c, a, b]);
    const weather = pairs(it.weather).map(([c]) => x(String(c.name), String(num(c.value)), may(c.name)));
    if (!weather.length) ctx.warn(it, 'No weather chosen: the biome needs at least one (for example Clear).');
    const dis = pairs(it.diseases).map(([c]) => x('li', [x('diseaseInc', String(c.name)), x('commonality', String(num(c.value)))], may(c.name)));
    const amb = (it.ambient || []).filter(idOk);
    const packs = (it.packAnimals || []).filter(idOk);
    const kids = [
      x('defName', it.defName),
      x('label', it.label),
      x('description', describe(it, ctx)),
      it.workerClass ? x('workerClass', it.workerClass) : x('generatesNaturally', 'false'),
      x('animalDensity', n(it.animalDensity, 0)),
      x('plantDensity', n(it.plantDensity, 0)),
      x('settlementSelectionWeight', n(it.settlementWeight, 1)),
      x('movementDifficulty', n(it.movementDifficulty, 1)),
      x('texture', tex),
      Number(it.forageability) > 0 ? x('forageability', n(it.forageability, 0)) : null,
      Number(it.forageability) > 0 && idOk(it.foragedFood) ? x('foragedFood', it.foragedFood) : null,
      x('wildPlantRegrowDays', n(it.wildPlantRegrowDays, 20)),
      it.allowFarmingCamps === false ? x('allowFarmingCamps', 'false') : null,
      amb.length ? x('soundsAmbient', li(amb)) : null,
      x('diseaseMtbDays', n(it.diseaseMtbDays, 50)),
      dis.length ? x('diseases', dis) : null,
      bands.length ? x('terrainsByFertility', bands.map(band)) : null,
      patches.length ? x('terrainPatchMakers', patches) : null,
      weather.length ? x('baseWeatherCommonalities', weather) : null,
      plants.length ? x('wildPlants', plants) : null,
      animals.length ? x('wildAnimals', animals) : null,
      packs.length ? x('allowedPackAnimals', li(packs)) : null,
    ];
    return { dir: 'Defs/BiomeDefs', xml: doc(x('Defs', [x('BiomeDef', kids)])), files };
  }

