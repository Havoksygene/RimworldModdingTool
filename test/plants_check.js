'use strict';
// Plant builder + natural rock walls. usage: node test/plants_check.js
const assert = require('assert');
global.window = global;
const SC = require('../renderer/modschema.js'),
  GEN = require('../renderer/modgen.js');
const sp = { single: { kind: 'file', id: 'x' } };
const P = SC.newProject();
P.meta.name = 'GreenMod';
P.meta.prefix = 'GM_';
const bush = SC.newItem('plant');
Object.assign(bush, { label: 'Blue Berry', harvestedThing: 'GM_BlueFruit', sowable: true, growMinTemp: 2, clusterWeight: 40, sprites: { single: sp } });
const tree = SC.newItem('plant');
tree.preset = 'tree';
SC.applyPlantPreset(tree);
Object.assign(tree, { label: 'Glass Tree', sprites: { single: sp } });
const flower = SC.newItem('plant');
flower.preset = 'flower';
SC.applyPlantPreset(flower);
Object.assign(flower, { label: 'Pale Moss', sprites: { single: sp } });
const rock = SC.newItem('building');
rock.preset = 'wall';
SC.applyBuildPreset(rock);
Object.assign(rock, { label: 'Violet Stone', natural: true, color: '#695f61', mineableThing: 'GM_VioletChunk', sprites: { atlas: sp } });
rock.stats.MaxHitPoints = 700;
const ore = SC.newItem('building');
ore.preset = 'wall';
SC.applyBuildPreset(ore);
Object.assign(ore, { label: 'Violet Ore', natural: true, rockKind: 'ore', mineableThing: 'GM_Violet', mineableYield: 30, veinSize: '20~30', sprites: { atlas: sp } });
P.items = [bush, tree, flower, rock, ore];
const r = GEN.generate(P);
assert.deepStrictEqual(r.errors, [], r.errors.join('\n'));
const get = (p) => (r.files.find((f) => f.path === p) || {}).text;
const b = get('Defs/ThingDefs_Plants/Plant_GM_BlueBerry.xml');
assert(/ParentName="BushBase"/.test(b) && /<texPath>Things\/Plant\/GreenMod\/GM_BlueBerry<\/texPath>/.test(b) && /Graphic_Random/.test(b), b);
assert(/<harvestedThingDef>GM_BlueFruit/.test(b) && /<harvestYield>10/.test(b) && /<harvestTag>Standard/.test(b) && /<sowTags>/.test(b) && /<minGrowthTemperature>2/.test(b) && /<wildClusterWeight>40/.test(b), b);
assert(r.files.some((f) => f.path === 'Textures/Things/Plant/GreenMod/GM_BlueBerry/GM_BlueBerryA.png' && f.keep));
const t = get('Defs/ThingDefs_Plants/Plant_GM_GlassTree.xml');
assert(/ParentName="TreeBase"/.test(t) && /<harvestedThingDef>WoodLog/.test(t) && /<mustBeWildToSow>true/.test(t) && !/<sowTags>/.test(t), t);
const f = get('Defs/ThingDefs_Plants/Plant_GM_PaleMoss.xml');
assert(/ParentName="PlantBase"/.test(f) && /<ingestible\/>/.test(f) && !/harvestedThingDef/.test(f), f);
assert(r.warnings.some((w) => /cannot harvest/.test(w.message)), 'flower without harvest warns');
const s = get('Defs/ThingDefs_Buildings/Building_GM_VioletStone.xml');
assert(/ParentName="UglyRockBase"/.test(s) && /<mineableThing>GM_VioletChunk/.test(s) && /<mineableDropChance>0.25/.test(s) && /<color>\(105,95,97\)/.test(s), s);
assert(!/costList|designationCategory|stuffCategories|isWall/.test(s) && /<MaxHitPoints>700/.test(s), s);
assert(/Textures\/Things\/Building\/GreenMod\/GM_VioletStone_Atlas.png/.test(r.files.map((x) => x.path).join('\n')));
const o = get('Defs/ThingDefs_Buildings/Building_GM_VioletOre.xml');
assert(/ParentName="RockBase"/.test(o) && /<isResourceRock>true/.test(o) && /<mineableYield>30/.test(o) && /<mineableScatterLumpSizeRange>20~30/.test(o) && /<veinMineable>true/.test(o), o);
console.log('PLANTS_OK');
