'use strict';
const assert = require('assert');
const U = require('../lib/update');
assert.ok(U.isNewer('v0.2.0', '0.1.0'));
assert.ok(U.isNewer('1.0.0', '0.9.9'));
assert.ok(U.isNewer('v0.10.0', '0.9.0'), 'numeric, not text, comparison');
assert.ok(!U.isNewer('v0.1.0', '0.1.0'));
assert.ok(!U.isNewer('0.0.9', '0.1.0'));
assert.ok(!U.isNewer('banana', '0.1.0'));
assert.ok(!U.isNewer('0.2.0', ''));
const rel = { tag_name: 'v0.2.0', html_url: 'https://github.com/Havoksygene/RimworldModdingTool/releases/tag/v0.2.0', body: 'x' };
assert.deepStrictEqual(U.fromRelease(rel, '0.1.0').version, '0.2.0');
assert.strictEqual(U.fromRelease(rel, '0.2.0'), null);
assert.strictEqual(U.fromRelease({ ...rel, prerelease: true }, '0.1.0'), null);
assert.strictEqual(U.fromRelease({ ...rel, draft: true }, '0.1.0'), null);
assert.strictEqual(U.fromRelease(null, '0.1.0'), null);
assert.ok(U.fromRelease({ ...rel, html_url: 'https://evil.example/x' }, '0.1.0').url.startsWith(U.PAGE_PREFIX), 'foreign links are replaced');
assert.ok(U.safeUrl(rel.html_url) && !U.safeUrl('https://evil.example/') && !U.safeUrl('file:///etc/passwd'));
console.log('update tests passed');
