'use strict';
// Chunk -> blocks, crafted items, crafted (sculpture-like) buildings. usage: node test/crafting_check.js
const assert = require('assert');
global.window = global;
const SC = require('../renderer/modschema.js'),
  GEN = require('../renderer/modgen.js');
const sp = { single: { kind: 'file', id: 'x' } };
const P = SC.newProject();
P.meta.name = 'CraftMod';
P.meta.prefix = 'CM_';
const chunk = SC.newItem('item');
chunk.preset = 'chunk';
SC.applyItemPreset(chunk);
Object.assign(chunk, { label: 'Violet Chunk', thingCategories: ['StoneChunks'], cutProducts: [{ name: 'CM_VioletBlocks', value: 20 }], sprites: { single: sp } });
const bad = SC.newItem('item');
bad.preset = 'chunk';
SC.applyItemPreset(bad);
Object.assign(bad, { label: 'Odd Chunk', cutProducts: [{ name: 'CM_VioletBlocks', value: 5 }], sprites: { single: sp } });
const part = SC.newItem('item');
Object.assign(part, { label: 'Violet Gear', craftable: true, cost: [{ name: 'Steel', value: 4 }], productCount: 3, craftSkill: 5, research: 'Smithing', workbenches: ['TableMachining'], sprites: { single: sp } });
part.stats.WorkToMake = 600;
const statue = SC.newItem('building');
statue.preset = 'crafted';
SC.applyBuildPreset(statue);
Object.assign(statue, { label: 'Violet Statue', sprites: { single: sp } });
P.items = [chunk, bad, part, statue];
const r = GEN.generate(P);
assert.deepStrictEqual(r.errors, [], r.errors.join('\n'));
const get = (p) => (r.files.find((f) => f.path === p) || {}).text;
const c = get('Defs/ThingDefs_Items/Item_CM_VioletChunk.xml');
assert(/<butcherProducts>\s*<CM_VioletBlocks>20<\/CM_VioletBlocks>/.test(c) && /<li>StoneChunks<\/li>/.test(c), c);
assert(r.warnings.some((w) => /not in the "StoneChunks"/.test(w.message) && w.item === 'Odd Chunk'), 'warns when not a stone chunk');
const g = get('Defs/ThingDefs_Items/Item_CM_VioletGear.xml');
assert(/<costList>\s*<Steel>4<\/Steel>/.test(g) && /<recipeMaker>/.test(g) && /<productCount>3/.test(g) && /<li>TableMachining<\/li>/.test(g) && /<WorkToMake>600/.test(g), g);
assert(/<researchPrerequisite>Smithing/.test(g) && /<Crafting>5<\/Crafting>/.test(g), g);
const b = get('Defs/ThingDefs_Buildings/Building_CM_VioletStatue.xml');
assert(/<minifiedDef>MinifiedThing/.test(b) && /<li>BuildingsArt<\/li>/.test(b) && /<recipeMaker>/.test(b) && /<workSkill>Artistic/.test(b) && /<li>TableSculpting<\/li>/.test(b), b);
assert(!/designationCategory|WorkToBuild/.test(b) && /<WorkToMake>5000/.test(b) && /<stuffCategories>/.test(b) && /<unfinishedThingDef>UnfinishedSculpture/.test(b), b);
console.log('CRAFTING_OK');
